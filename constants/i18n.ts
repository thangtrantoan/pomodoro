/** Số đếm viết chữ cho "… of four in this set" — chỉ dùng ở bản `en` */
function asWord(n: number): string {
  return ['zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven'][n] ?? `${n}`;
}

