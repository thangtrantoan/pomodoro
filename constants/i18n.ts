/** "Third of four in this set" — design dùng số thứ tự viết chữ cho vị trí phiên */
function ordinal(n: number): string {
  return (
    ['Zeroth', 'First', 'Second', 'Third', 'Fourth', 'Fifth', 'Sixth', 'Seventh'][n] ?? `#${n}`
  );
}

